# Original List
my_list = [1, 2, 2, 3]

# List → Tuple
my_tuple = tuple(my_list)

# List → Set
my_set = set(my_list)

print("List:", my_list)
print("Tuple:", my_tuple)
print("Set:", my_set)

# Tuple → List
print("Tuple -> List:", list(my_tuple))

# Tuple → Set
print("Tuple -> Set:", set(my_tuple))

# Set → List
print("Set -> List:", list(my_set))

# Set → Tuple
print("Set -> Tuple:", tuple(my_set))